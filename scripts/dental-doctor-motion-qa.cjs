const assert=require('node:assert/strict')
const fs=require('node:fs/promises')
const path=require('node:path')
const {chromium}=require('/Users/hhm/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright')
const root=path.resolve(__dirname,'..'),out=path.join(root,'artifacts/figma-doctors-2026-10-20')
const selector=id=>`[data-figma-node="${id}"]`
const read=async name=>JSON.parse(await fs.readFile(path.join(root,`docs/figma-source/doctors/dental-${name}/dialog-model-2026-10-20.json`),'utf8'))
const url=(process.env.HUANYU_QA_URL||'http://127.0.0.1:5174').replace(/\/$/,'')+'/dental'
async function enter(page){
  await page.goto(url,{waitUntil:'networkidle'})
  await page.getByRole('button',{name:/02 城市与医生匹配/}).click()
  await page.locator('.dental-doctor-card__button').first().click()
}
async function main(){
  await fs.mkdir(out,{recursive:true})
  const browser=await chromium.launch({headless:true,executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome'})
  const report={createdAt:'',desktop:[],motion:{},errors:[]}
  try{
    for(const [width,height] of [[1024,600],[1440,754],[1920,1080]]){
      const page=await browser.newPage({viewport:{width,height},reducedMotion:'reduce'})
      page.on('pageerror',error=>report.errors.push(error.message))
      await enter(page)
      const y=await page.evaluate(()=>scrollY),states=[]
      for(const [index,name] of ['profile','cases','reviews'].entries()){
        if(index)await page.locator('.dental-source-dialog [role="tab"]').nth(index).click()
        const model=await read(name)
        await page.locator(`dialog${selector(model.frame)}`).waitFor({state:'visible'})
        await page.locator(`dialog ${selector(model.panel)}`).waitFor({state:'visible'})
        await page.waitForFunction(expected=>document.querySelector('.dental-source-dialog__clip')?.getBoundingClientRect().height===expected,model.mask?.height??model.height)
        const clip=page.locator('.dental-source-dialog__clip')
        const dialog=page.locator('dialog[open]')
        await page.evaluate(()=>document.fonts.ready)
        const box=await clip.boundingBox()
        assert.equal(box.width,896);assert.equal(box.height,model.mask?.height??model.height)
        assert.ok(box.x>=24&&box.x+box.width<=width-24,`${name}/${width}: horizontal fit`)
        await dialog.evaluate(el=>el.scrollTo({top:el.scrollHeight,behavior:'instant'}))
        await clip.evaluate(el=>el.scrollTo({top:el.scrollHeight,behavior:'instant'}))
        await page.evaluate(()=>new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve))))
        const bottom=await clip.boundingBox()
        assert.ok(bottom.y+bottom.height<=height-38,`${name}/${width}: bottom not reachable`)
        const last=page.locator(`dialog ${selector(model.panel)} .home-source-node--text`).last()
        const lastBox=await last.boundingBox()
        assert.ok(lastBox.y+lastBox.height<=bottom.y+bottom.height+1,`${name}: final text inaccessible`)
        const overflow=await dialog.evaluate(el=>el.scrollWidth>el.clientWidth)
        assert.equal(overflow,false)
        const broken=await dialog.locator('img').evaluateAll(images=>images.filter(image=>!image.complete||!image.naturalWidth).map(image=>image.src))
        assert.deepEqual(broken,[])
        await dialog.evaluate(el=>el.scrollTop=0)
        await clip.evaluate(el=>el.scrollTop=0)
        await page.screenshot({path:path.join(out,`dental-${name}-short-${width}.png`)})
        states.push({name,box,bottomReachable:true,lastTextReachable:true,overflow:false,brokenImages:broken})
      }
      await page.keyboard.press('Escape')
      assert.equal(await page.locator('dialog[open]').count(),0)
      assert.equal(await page.evaluate(()=>scrollY),y)
      assert.ok(await page.locator('.dental-doctor-card__button').first().evaluate(el=>document.activeElement===el))
      report.desktop.push({width,height,states,scrollRestore:true,focusRestore:true})
      await page.close()
    }
    const page=await browser.newPage({viewport:{width:1440,height:900},reducedMotion:'no-preference'})
    page.on('pageerror',error=>report.errors.push(error.message))
    await enter(page)
    const position=page.locator('.dental-source-dialog__position')
    assert.ok((await position.evaluate(el=>getComputedStyle(el).animationName)).startsWith('dental-dialog-in'))
    await page.screenshot({path:path.join(out,'dental-motion-mid.png')})
    await page.waitForTimeout(380)
    await page.locator('.dental-source-dialog [role="tab"]').nth(1).click()
    const animations=await page.locator('dialog').evaluate(el=>el.getAnimations({subtree:true}).filter(animation=>animation.playState==='running').map(animation=>animation.effect.getKeyframes()))
    assert.ok(animations.some(frames=>frames[0].opacity==='0'&&frames.at(-1).opacity==='1'),'Tab content must fade')
    assert.ok(animations.every(frames=>frames.every(frame=>!frame.transform)),'Tab animation must not change source geometry')
    await page.screenshot({path:path.join(out,'dental-tab-mid.png')})
    for(const index of [2,0,1,2,1])await page.locator('.dental-source-dialog [role="tab"]').nth(index).click()
    await page.waitForTimeout(300)
    assert.equal(await page.locator('.dental-source-dialog [role="tab"][aria-selected="true"]').count(),1)
    assert.equal(await page.locator('dialog').evaluate(el=>el.getAnimations({subtree:true}).filter(animation=>animation.playState==='running').length),0)
    await page.screenshot({path:path.join(out,'dental-motion-settled.png')})
    await page.emulateMedia({reducedMotion:'reduce'})
    await page.evaluate(()=>new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve))))
    assert.equal(await position.evaluate(el=>getComputedStyle(el).animationName),'none')
    await page.locator('.dental-source-dialog [role="tab"]').first().click()
    await page.evaluate(()=>new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve))))
    assert.equal(await page.locator('dialog').evaluate(el=>el.getAnimations({subtree:true}).length),0)
    await page.keyboard.press('Escape')
    report.motion={modalEnter:true,tabFade:true,noTabGeometryAnimation:true,rapidSwitch:true,reducedMotion:true}
    assert.deepEqual(report.errors,[])
    report.createdAt=new Date().toISOString()
    await fs.writeFile(path.join(out,'dental-motion-qa.json'),JSON.stringify(report,null,2)+'\n')
    console.log(JSON.stringify({createdAt:report.createdAt,desktop:report.desktop.length,motion:report.motion,errors:report.errors}))
  }finally{await browser.close()}
}
main().catch(error=>{console.error(error);process.exitCode=1})
