// Geometry regressions for the translated Figma renderer. Browser/font and
// visual checks are separate; this suite never substitutes for screenshots.
const test=require('node:test')
const assert=require('node:assert/strict')
const fs=require('node:fs')
const vm=require('node:vm')
const ts=require('typescript')
const output=ts.transpileModule(fs.readFileSync('src/i18n/sourceLayout.ts','utf8'),{compilerOptions:{target:ts.ScriptTarget.ES2020,module:ts.ModuleKind.CommonJS}}).outputText
const moduleObject={exports:{}}
vm.runInNewContext(output,{module:moduleObject,exports:moduleObject.exports,document:{createElement:()=>({getContext:()=>({font:'',measureText(text){return {width:text.length*Number(this.font.match(/([\d.]+)px/)?.[1]||16)/2}}})})}})
const {sourceLocaleLayout}=moduleObject.exports
const node=(id,{x=0,y=0,width=300,height=40,text='',css='',layout='',children=[]}={})=>({id,name:id,type:text?'TEXT':'FRAME',x,y,width,height,visible:true,text,css:`position:absolute;left:${x}px;top:${y}px;width:${width}px;height:${height}px;${text?'font-size:16px;line-height:20px;':''}${css}`,layoutCss:layout,children})
const px=(layout,id,property)=>Number([...layout.styles[id].matchAll(new RegExp(`${property}:(-?[\\d.]+)px`,'g'))].at(-1)[1])
test('mirrored portrait keeps its native anchor; translated identity uses the remaining column',()=>{
 const image=node('portrait',{x:60,width:60,height:60,css:'transform-origin:0 0;transform:matrix(-1,0,0,1,0,0);'})
 const title=node('title',{width:100,height:20,text:'医生'})
 const identity=node('identity',{x:72,width:100,height:20,layout:'display:flex;flex-direction:column;',children:[title]})
 const root=node('row',{width:300,height:60,layout:'display:flex;gap:12px;',children:[image,identity]})
 const result=sourceLocaleLayout(root,()=> 'International specialist')
 assert.equal(px(result,'portrait','left'),60)
 assert.equal(px(result,'portrait','width'),60)
 assert.equal(px(result,'identity','left'),72)
 assert.equal(px(result,'identity','width'),228)
 assert.equal(px(result,'title','width'),228)
})
test('collapsed accordion stays collapsed after long-copy translation',()=>{
 const detail=node('detail',{height:120,children:[node('copy',{text:'详细说明',height:120})]})
 const root=node('root',{height:120,children:[detail]})
 const result=sourceLocaleLayout(root,()=> 'A long translated explanation '.repeat(20),{styles:{detail:'height:0px;overflow:hidden;'}})
 assert.equal(px(result,'detail','height'),0)
 assert.equal(result.height,120)
})
test('card widths and gaps stay fixed; rows move below their tallest translated card',()=>{
 const card=(id,x,y,text)=>node(id,{x,y,width:300,height:100,children:[node(`${id}-copy`,{width:300,height:20,text})]})
 const root=node('grid',{width:624,height:224,children:[card('a',0,0,'长文'),card('b',324,0,'短文'),card('c',0,124,'短文')]})
 const result=sourceLocaleLayout(root,text=>text==='长文'?'Medical services '.repeat(30):'Care')
 assert.equal(px(result,'a','width'),300)
 assert.equal(px(result,'b','left'),324)
 assert.equal(px(result,'b','height'),px(result,'a','height'))
 assert.equal(px(result,'c','top'),px(result,'a','height')+24)
})
test('the final percentage width overrides an old exported pixel width',()=>{
 const root=node('root',{width:300,children:[node('copy',{width:30,height:20,text:'说明',css:'width:100%;'})]})
 const result=sourceLocaleLayout(root,()=> 'Full width translated copy')
 assert.equal(px(result,'copy','width'),300)
})
test('wide background images keep their full-bleed dimensions',()=>{
 const background=node('image',{x:-240,width:1920,height:500,css:'background:url(/test.webp) center/cover;'})
 const root=node('root',{width:1440,height:500,children:[background]})
 const result=sourceLocaleLayout(root,text=>text)
 assert.equal(px(result,'image','width'),1920)
 assert.equal(px(result,'image','left'),-240)
})
test('centered headings grow around the center instead of inheriting their old alignment offset as padding',()=>{
 const heading=node('heading',{x:350,width:300,height:20,layout:'display:flex;flex-direction:column;align-items:center;',children:[node('copy',{width:300,height:20,text:'标题',css:'text-align:center;'})]})
 const root=node('root',{width:1000,height:120,layout:'display:flex;flex-direction:column;align-items:center;',children:[heading]})
 const result=sourceLocaleLayout(root,()=> 'A considerably longer translated heading across the page')
 assert.ok(px(result,'heading','width')>300)
 assert.equal(px(result,'heading','left')+px(result,'heading','width')/2,500)
 assert.ok(px(result,'heading','left')+px(result,'heading','width')<=1000)
})
test('a centered button retains its horizontal padding with a longer label and icon',()=>{
 const root=node('button',{width:240,height:48,layout:'display:flex;justify-content:center;align-items:center;padding:12px 24px;',children:[node('label',{x:64,width:80,height:20,text:'详情'}),node('icon',{x:152,width:24,height:24})]})
 const result=sourceLocaleLayout(root,()=> 'Read the full details')
 assert.ok(px(result,'label','left')>=24)
 assert.ok(px(result,'icon','left')+24<=216)
})
test('absolutely positioned content stays in its authored column when its copy grows',()=>{
 const column=node('column',{x:526,width:802,height:100,layout:'display:flex;flex-direction:column;position:absolute;',children:[node('heading',{width:400,height:20,text:'标题'})]})
 const root=node('section',{width:1440,height:100,layout:'display:flex;flex-direction:column;align-items:center;',children:[column]})
 const result=sourceLocaleLayout(root,()=> 'An extended heading '.repeat(8))
 assert.equal(px(result,'column','left'),526)
 assert.equal(px(result,'column','width'),802)
 assert.ok(px(result,'heading','width')<=802)
})
test('a translated count cannot squeeze an unchanged native rating into a narrower badge',()=>{
 const rating=node('rating',{width:24,height:20,text:'5.0'});rating.textLines=[{runs:[{text:'5.0',css:''}],css:'width:24px;'}]
 const badge=node('badge',{width:24,height:20,layout:'display:flex;',children:[rating]})
 const label=node('label',{x:32,width:80,height:20,text:'评价'})
 const root=node('row',{width:112,height:20,layout:'display:flex;gap:8px;',children:[badge,label]})
 const result=sourceLocaleLayout(root,text=>text==='评价'?'Patient reviews and ratings':text)
 assert.equal(px(result,'rating','width'),24)
 assert.equal(px(result,'badge','width'),24)
 assert.equal(px(result,'label','left'),32)
 assert.ok(px(result,'label','width')<=80)
})
