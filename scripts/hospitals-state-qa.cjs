const fs = require('node:fs')
const path = require('node:path')
const assert = require('node:assert/strict')
const { chromium } = require('/tmp/huanyu-visual-qa-tools/node_modules/playwright')
const out = path.resolve(process.env.HUANYU_QA_OUT || 'docs/figma-verification/hospitals/2026-09-29')
const origin = process.env.HUANYU_QA_URL || 'http://127.0.0.1:5173'
async function main() {
  const browser = await chromium.launch({ headless:true })
  try {
    const page = await browser.newPage({viewport:{width:1440,height:900}})
    const errors=[],results=[]
    page.on('pageerror',error=>errors.push(error.message))
    for(const width of [1440,1024,768,390]) {
      await page.setViewportSize({width,height:900})
      await page.goto(`${origin}/hospitals`,{waitUntil:'networkidle'})
      await page.waitForTimeout(900)
      assert.equal(await page.locator('.hospital-grid article').count(),8)
      for(const city of ['上海','广州','深圳','全部','北京']) {
        const button=page.getByRole('button',{name:city,exact:true})
        await button.focus()
        await page.keyboard.press(city==='广州'?'Space':'Enter')
        assert.equal(await button.getAttribute('aria-pressed'),'true')
        await page.waitForFunction(() => [...document.querySelectorAll('.hospital-grid article')].every(el=>getComputedStyle(el).opacity==='1'))
        const visible=await page.locator('.hospital-grid article').evaluateAll(elements=>elements.every(el=>getComputedStyle(el).opacity==='1'))
        assert.ok(visible,`${width}/${city}: filtered cards hidden by reveal`)
      }
      const detail=page.locator('.hospital-actions button').first()
      await detail.click()
      const dialog=page.locator('.hospital-modal')
      await dialog.waitFor({state:'visible'})
      assert.equal(await page.locator(':focus').getAttribute('aria-label'),'关闭')
      await page.keyboard.press('Shift+Tab')
      assert.equal(await page.locator(':focus').textContent(),'医院官网')
      await page.keyboard.press('Tab')
      assert.equal(await page.locator(':focus').getAttribute('aria-label'),'关闭')
      await page.waitForFunction(() => {
        const dialog = document.querySelector('.hospital-modal')
        const panel = document.querySelector('.hospital-modal__panel')
        return dialog && panel && getComputedStyle(dialog).opacity === '1' && getComputedStyle(panel).transform === 'none'
      })
      await page.screenshot({path:path.join(out,`detail-${width}.png`)})
      await page.keyboard.press('Escape')
      await dialog.waitFor({state:'hidden'})
      assert.equal((await page.locator(':focus').textContent()).trim(),'查看详情')
      assert.equal(await page.evaluate(()=>document.body.classList.contains('scroll-locked')),false)
      await detail.click()
      await dialog.waitFor({state:'visible'})
      await dialog.getByRole('button',{name:'预约咨询'}).click()
      const consultation=page.locator('.consult-overlay')
      await consultation.waitFor({state:'visible'})
      assert.equal(await page.locator(':focus').getAttribute('id'),'consult-name')
      assert.equal(await page.evaluate(()=>document.body.classList.contains('scroll-locked')),false)
      await page.keyboard.press('Escape')
      await consultation.waitFor({state:'hidden'})
      await page.getByRole('button',{name:'预约咨询',exact:true}).first().click()
      await consultation.waitFor({state:'visible'})
      await page.keyboard.press('Escape')
      await consultation.waitFor({state:'hidden'})
      const geometry=await page.evaluate(()=>({width:innerWidth,scrollWidth:document.documentElement.scrollWidth,broken:[...document.images].filter(i=>!i.complete||!i.naturalWidth).map(i=>i.src)}))
      assert.equal(geometry.scrollWidth,width,`${width}: horizontal overflow`)
      assert.equal(geometry.broken.length,0)
      for(const attribute of ['mailto:','tel:','https://wa.me/'])assert.ok(await page.locator(`footer a[href^="${attribute}"]`).count())
      await page.locator('.header-logo').click()
      await page.waitForURL(`${origin}/`)
      results.push({...geometry,cityFilters:5,keyboard:true,modalFocusTrap:true,escape:true,focusRestore:true,consultation:true,homeLink:true})
    }
    await page.setViewportSize({width:1440,height:900})
    await page.goto(`${origin}/hospitals`,{waitUntil:'networkidle'})
    const card=page.locator('.hospital-grid article').first()
    await card.scrollIntoViewIfNeeded()
    await page.waitForTimeout(900)
    await card.hover()
    await page.waitForTimeout(450)
    const hover=await card.evaluate(el=>({transform:getComputedStyle(el).transform,width:el.getBoundingClientRect().width,height:el.getBoundingClientRect().height}))
    assert.ok(hover.transform.includes('-6'),JSON.stringify(hover))
    await page.screenshot({path:path.join(out,'hover-1440.png')})
    await page.emulateMedia({reducedMotion:'reduce'})
    await page.waitForTimeout(300)
    const reduced=await card.evaluate(el=>({transform:getComputedStyle(el).transform,transition:getComputedStyle(el).transitionDuration,opacity:getComputedStyle(el).opacity}))
    assert.equal(reduced.transform,'none')
    assert.ok(parseFloat(reduced.transition) <= .0001, `Reduced-motion duration ${reduced.transition}`)
    assert.equal(reduced.opacity,'1')
    assert.equal(errors.length,0,errors.join('\n'))
    fs.writeFileSync(path.join(out,'state-results.json'),JSON.stringify({results,hover,reduced,errors},null,2)+'\n')
    console.log(JSON.stringify({viewports:results.length,filters:20,modalFocusTrap:true,consultation:true,hover,reduced,errors}))
  } finally {await browser.close()}
}
fs.mkdirSync(out,{recursive:true})
main().catch(e=>{console.error(e);process.exitCode=1})
