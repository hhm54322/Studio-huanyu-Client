const fs = require('node:fs')
const path = require('node:path')
const assert = require('node:assert/strict')
const { chromium } = require('/tmp/huanyu-visual-qa-tools/node_modules/playwright')
const out = path.resolve(process.env.HUANYU_QA_OUT || 'docs/figma-verification/diseases/2026-09-29')
const url = `${process.env.HUANYU_QA_URL || 'http://127.0.0.1:5173'}/diseases-technologies`
async function main() {
  const browser = await chromium.launch({ headless: true })
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 900 } })
    const errors = [], results = []
    page.on('pageerror', error => errors.push(error.message))
    for (const width of [1440, 1024, 768, 390]) {
      await page.setViewportSize({ width, height: width === 1440 ? 900 : 844 })
      await page.goto(url, { waitUntil: 'networkidle' })
      await page.evaluate(() => document.fonts.ready)
      const cards = page.locator('.disease-card')
      assert.equal(await cards.count(), 14)
      for (let top = 0; top < await page.evaluate(() => document.documentElement.scrollHeight); top += 550) {
        await page.evaluate(top => scrollTo(0, top), top)
        await page.waitForTimeout(80)
      }
      await page.waitForTimeout(650)
      await page.waitForFunction(() => [...document.querySelectorAll('.disease-card')].every(el => getComputedStyle(el).opacity === '1'))
      const reveal = await cards.evaluateAll(els => els.map(el => ({ nodeId:el.dataset.figmaNode, opacity:getComputedStyle(el).opacity, className:el.className })))
      assert.ok(reveal.every(el => el.opacity === '1'), `${width}: ${JSON.stringify(reveal.filter(el => el.opacity !== '1'))}`)
      const geometry = await page.evaluate(() => ({ width: innerWidth, scrollWidth: document.documentElement.scrollWidth, broken: [...document.images].filter(img => !img.complete || !img.naturalWidth).map(img => img.src) }))
      assert.equal(geometry.scrollWidth, width, `${width}: overflow`)
      assert.equal(geometry.broken.length, 0, `${width}: broken assets`)
      await page.evaluate(() => scrollTo(0, 0))
      const search = page.getByRole('searchbox', { name: '搜索疾病' })
      await search.fill('牙科')
      assert.equal(await cards.count(), 1)
      assert.equal(await cards.locator('h2').textContent(), '牙科')
      await cards.first().scrollIntoViewIfNeeded()
      await page.waitForTimeout(650)
      await page.screenshot({ path: path.join(out, `search-${width}.png`) })
      await cards.first().click()
      await page.waitForURL('**/dental')
      await page.goto(url, { waitUntil: 'networkidle' })
      await search.fill('MDT')
      assert.equal(await cards.count(), 1)
      await search.fill('All-ON')
      assert.equal(await cards.count(), 1)
      await search.fill('没有这项疾病123')
      assert.equal(await cards.count(), 0)
      const empty = page.getByRole('status').filter({ hasText: '暂未找到相关疾病' })
      assert.equal(await empty.isVisible(), true)
      await empty.scrollIntoViewIfNeeded()
      await page.screenshot({ path: path.join(out, `empty-${width}.png`) })
      await page.getByRole('button', { name: '查看全部疾病', exact: true }).click()
      assert.equal(await cards.count(), 14)
      assert.equal(await search.inputValue(), '')
      const unavailable = cards.filter({ hasText: '肿瘤科' })
      assert.equal(await unavailable.getAttribute('href'), null)
      await page.getByRole('link', { name: '提交病历', exact: true }).click()
      await page.waitForURL('**/report')
      await page.goto(url, { waitUntil: 'networkidle' })
      const trigger = page.getByRole('button', { name: '免费咨询阿宁', exact: true })
      await trigger.click()
      const dialog = page.getByRole('dialog')
      await dialog.waitFor({ state: 'visible' })
      assert.equal(await page.locator(':focus').getAttribute('id'), 'consult-name')
      const close = dialog.getByRole('button', { name: '关闭', exact: true })
      await close.focus()
      await page.keyboard.press('Shift+Tab')
      assert.equal(await close.evaluate(el => el === document.activeElement), false)
      await page.keyboard.press('Tab')
      assert.equal(await close.evaluate(el => el === document.activeElement), true)
      await page.screenshot({ path: path.join(out, `consult-${width}.png`) })
      await page.keyboard.press('Escape')
      await dialog.waitFor({ state: 'hidden' })
      assert.equal(await trigger.evaluate(el => el === document.activeElement), true)
      assert.equal(await page.evaluate(() => document.body.style.overflow), '')
      results.push({ ...geometry, search:true, featureSearch:true, reset:true, empty:true, dental:true, report:true, unfinishedDisabled:true, consultation:true, focusTrap:true, focusRestore:true, escape:true, reveal:true })
    }
    await page.setViewportSize({ width:1440, height:900 })
    await page.goto(url, { waitUntil:'networkidle' })
    const card = page.locator('.disease-card').first()
    await card.scrollIntoViewIfNeeded()
    await page.waitForTimeout(900)
    const rest = await card.boundingBox()
    await card.hover()
    await page.waitForTimeout(600)
    const hover = await card.evaluate(el => ({ transform:getComputedStyle(el).transform, width:el.getBoundingClientRect().width, height:el.getBoundingClientRect().height }))
    assert.ok(hover.transform.includes('-6'), JSON.stringify(hover))
    assert.equal(hover.width, rest.width)
    assert.equal(hover.height, rest.height)
    await page.screenshot({ path:path.join(out,'hover-1440.png') })
    await page.emulateMedia({ reducedMotion:'reduce' })
    const reduced = await card.evaluate(el => ({ transform:getComputedStyle(el).transform, transition:getComputedStyle(el).transitionDuration, opacity:getComputedStyle(el).opacity }))
    assert.equal(reduced.transform, 'none')
    assert.ok(parseFloat(reduced.transition) <= .0001, `Reduced-motion duration: ${reduced.transition}`)
    assert.equal(reduced.opacity, '1')
    assert.equal(errors.length, 0, errors.join('\n'))
    fs.writeFileSync(path.join(out,'state-results.json'),JSON.stringify({ results, hover, reduced, errors },null,2)+'\n')
    console.log(JSON.stringify({ viewports:results.length,hover,reduced,errors }))
  } finally { await browser.close() }
}
fs.mkdirSync(out,{recursive:true})
main().catch(error=>{console.error(error);process.exitCode=1})
